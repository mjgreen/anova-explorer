script <- normalizePath(sub("^--file=", "", grep("^--file=", commandArgs(), value = TRUE)[1]), mustWork = TRUE)
root <- dirname(script)
source(file.path(root, "scripts", "library.R"))
anova_use_library(root)
port <- suppressWarnings(as.integer(Sys.getenv("ANOVA_PORT", "3841")))
if (length(port) != 1L || is.na(port) || port < 1024L || port > 65535L) stop("ANOVA_PORT must be a number from 1024 to 65535.")
host <- Sys.getenv("ANOVA_BIND_HOST", "127.0.0.1")
if (!host %in% c("127.0.0.1", "0.0.0.0")) stop("ANOVA_BIND_HOST must be 127.0.0.1 or 0.0.0.0.")
options(shiny.useragg = FALSE, shiny.usecairo = FALSE)
setwd(root)
shiny::runApp(root, host = host, port = port, launch.browser = FALSE)
